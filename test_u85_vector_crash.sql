-- 测试向量索引崩溃问题 - 使用表U85
-- 复现EXPLAIN和SELECT导致程序崩溃的问题

-- 清理环境
DROP TABLE IF EXISTS U85;

-- 创建测试表
CREATE TABLE U85 (ID INT, C1 VECTOR(3));

-- 创建向量索引（此时表为空）
CREATE VECTOR INDEX V_I_U85 ON U85(C1) WITH(TYPE=IVFFLAT, DISTANCE=L2_DISTANCE, LISTS=1, PROBES=1);

-- 插入测试数据
INSERT INTO U85 VALUES(1, '[1,2,3]');
INSERT INTO U85 VALUES(2, '[2,3,4]');
INSERT INTO U85 VALUES(3, '[3,4,5]');
INSERT INTO U85 VALUES(4, '[4,5,6]');
INSERT INTO U85 VALUES(5, '[5,6,7]');

-- 测试1：EXPLAIN查询（预期崩溃）
EXPLAIN SELECT C1, L2_DISTANCE(C1, '[1,2,3]') FROM U85 ORDER BY L2_DISTANCE(C1, '[1,2,3]') LIMIT 3;

-- 测试2：实际查询（预期崩溃）
SELECT C1, L2_DISTANCE(C1, '[1,2,3]') FROM U85 ORDER BY L2_DISTANCE(C1, '[1,2,3]') LIMIT 3;

-- 清理
DROP TABLE U85;
